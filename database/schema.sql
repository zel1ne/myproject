-- Добавить оценку
CREATE OR ALTER PROCEDURE dbo.usp_ДобавитьОценку
    @СтудентID       INT,
    @ДисциплинаID    INT,
    @ПреподавательID INT,
    @ТипРаботы       NVARCHAR(50),
    @Оценка          TINYINT,
    @Дата            DATE = NULL,
    @Комментарий     NVARCHAR(500) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF @Дата IS NULL SET @Дата = CAST(GETDATE() AS DATE);

    INSERT INTO dbo.Оценки
        (СтудентID, ДисциплинаID, ПреподавательID, ТипРаботы, Оценка, Дата, Комментарий)
    VALUES
        (@СтудентID, @ДисциплинаID, @ПреподавательID, @ТипРаботы, @Оценка, @Дата, @Комментарий);

    SELECT SCOPE_IDENTITY() AS НоваяОценкаID;
END;
GO

-- Отметить посещаемость
CREATE OR ALTER PROCEDURE dbo.usp_ОтметитьПосещаемость
    @СтудентID       INT,
    @ДисциплинаID    INT,
    @ПреподавательID INT,
    @Дата            DATE,
    @Статус          NCHAR(1)
AS
BEGIN
    SET NOCOUNT ON;
    -- Обновить если уже есть, иначе вставить
    MERGE dbo.Посещаемость AS target
    USING (SELECT @СтудентID, @ДисциплинаID, @Дата) AS source (СтудентID, ДисциплинаID, Дата)
    ON target.СтудентID = source.СтудентID
       AND target.ДисциплинаID = source.ДисциплинаID
       AND target.Дата = source.Дата
    WHEN MATCHED THEN
        UPDATE SET Статус = @Статус, ПреподавательID = @ПреподавательID
    WHEN NOT MATCHED THEN
        INSERT (СтудентID, ДисциплинаID, ПреподавательID, Дата, Статус)
        VALUES (@СтудентID, @ДисциплинаID, @ПреподавательID, @Дата, @Статус);
END;
GO

-- Отчёт: средний балл по группе за семестр
CREATE OR ALTER PROCEDURE dbo.usp_ОтчётПоГруппе
    @ГруппаID    INT,
    @УчебныйГод  NVARCHAR(9) = '2025/2026',
    @Семестр     TINYINT     = 1
AS
BEGIN
    SET NOCOUNT ON;
    SELECT
        п.ФИО              AS Студент,
        д.Название         AS Дисциплина,
        о.ТипРаботы,
        о.Оценка,
        о.Дата
    FROM dbo.Оценки           о
    JOIN dbo.Студенты         с  ON о.СтудентID    = с.СтудентID
    JOIN dbo.Пользователи     п  ON с.ПользовательID = п.ПользовательID
    JOIN dbo.Дисциплины       д  ON о.ДисциплинаID = д.ДисциплинаID
    WHERE с.ГруппаID    = @ГруппаID
      AND о.УчебныйГод  = @УчебныйГод
      AND о.Семестр     = @Семестр
    ORDER BY п.ФИО, д.Название, о.Дата;
END;
GO

