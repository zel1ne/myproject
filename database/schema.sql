-- ============================================================
-- 1. СПРАВОЧНИК СПЕЦИАЛЬНОСТЕЙ
-- ============================================================
CREATE TABLE dbo.Специальности
(
    СпециальностьID INT           IDENTITY(1,1) PRIMARY KEY,
    Код             VARCHAR(20)   NOT NULL UNIQUE,
    Название        NVARCHAR(200) NOT NULL,
    Описание        NVARCHAR(500) NULL,
    Активна         BIT           NOT NULL DEFAULT 1,
    ДатаСоздания    DATETIME2     NOT NULL DEFAULT GETDATE()
);
GO

-- ============================================================
-- 2. УЧЕБНЫЕ ГРУППЫ
-- ============================================================
CREATE TABLE dbo.Группы
(
    ГруппаID        INT           IDENTITY(1,1) PRIMARY KEY,
    Название        NVARCHAR(50)  NOT NULL UNIQUE,
    СпециальностьID INT           NOT NULL,
    ГодНабора       SMALLINT      NOT NULL,
    Курс            TINYINT       NOT NULL CHECK (Курс BETWEEN 1 AND 4),
    Активна         BIT           NOT NULL DEFAULT 1,
    ДатаСоздания    DATETIME2     NOT NULL DEFAULT GETDATE(),

    CONSTRAINT FK_Группы_Специальности
        FOREIGN KEY (СпециальностьID) REFERENCES dbo.Специальности(СпециальностьID)
);
GO

-- ============================================================
-- 3. ПОЛЬЗОВАТЕЛИ (аккаунты входа)
-- ============================================================
CREATE TABLE dbo.Пользователи
(
    ПользовательID  INT           IDENTITY(1,1) PRIMARY KEY,
    Email           NVARCHAR(150) NOT NULL UNIQUE,
    ХешПароля       NVARCHAR(255) NOT NULL,        -- bcrypt hash
    Роль            NVARCHAR(20)  NOT NULL
        CHECK (Роль IN ('admin', 'teacher', 'student')),
    ФИО             NVARCHAR(200) NOT NULL,
    Телефон         VARCHAR(20)   NULL,
    Активен         BIT           NOT NULL DEFAULT 1,
    ДатаСоздания    DATETIME2     NOT NULL DEFAULT GETDATE(),
    ПоследнийВход   DATETIME2     NULL
);
GO

-- ============================================================
-- 4. ПРЕПОДАВАТЕЛИ
-- ============================================================
CREATE TABLE dbo.Преподаватели
(
    ПреподавательID INT           IDENTITY(1,1) PRIMARY KEY,
    ПользовательID  INT           NOT NULL UNIQUE,
    Должность       NVARCHAR(100) NULL,
    Кафедра         NVARCHAR(100) NULL,

    CONSTRAINT FK_Преподаватели_Пользователи
        FOREIGN KEY (ПользовательID) REFERENCES dbo.Пользователи(ПользовательID)
);
GO

-- ============================================================
-- 5. СТУДЕНТЫ
-- ============================================================
CREATE TABLE dbo.Студенты
(
    СтудентID       INT           IDENTITY(1,1) PRIMARY KEY,
    ПользовательID  INT           NOT NULL UNIQUE,
    ГруппаID        INT           NOT NULL,
    НомерЗачётки    VARCHAR(20)   NOT NULL UNIQUE,
    ДатаРождения    DATE          NULL,
    Адрес           NVARCHAR(300) NULL,
    ГодПоступления  SMALLINT      NULL,
    Статус          NVARCHAR(20)  NOT NULL DEFAULT 'Активный'
        CHECK (Статус IN ('Активный', 'Академотпуск', 'Отчислен', 'Выпустился')),
    ДатаСоздания    DATETIME2     NOT NULL DEFAULT GETDATE(),

    CONSTRAINT FK_Студенты_Пользователи
        FOREIGN KEY (ПользовательID) REFERENCES dbo.Пользователи(ПользовательID),
    CONSTRAINT FK_Студенты_Группы
        FOREIGN KEY (ГруппаID) REFERENCES dbo.Группы(ГруппаID)
);
GO

-- ============================================================
-- 6. ДИСЦИПЛИНЫ
-- ============================================================
CREATE TABLE dbo.Дисциплины
(
    ДисциплинаID    INT           IDENTITY(1,1) PRIMARY KEY,
    Код             VARCHAR(10)   NOT NULL UNIQUE,
    Название        NVARCHAR(200) NOT NULL,
    Описание        NVARCHAR(500) NULL,
    ЧасовВсего      SMALLINT      NULL,
    Активна         BIT           NOT NULL DEFAULT 1
);
GO

-- ============================================================
-- 7. НАЗНАЧЕНИЯ ДИСЦИПЛИН (преподаватель → группа → дисциплина)
-- ============================================================
CREATE TABLE dbo.НазначенияДисциплин
(
    НазначениеID    INT         IDENTITY(1,1) PRIMARY KEY,
    ДисциплинаID    INT         NOT NULL,
    ГруппаID        INT         NOT NULL,
    ПреподавательID INT         NOT NULL,
    Семестр         TINYINT     NOT NULL CHECK (Семестр BETWEEN 1 AND 2),
    УчебныйГод      NVARCHAR(9) NOT NULL,       -- напр. '2025/2026'
    Активно         BIT         NOT NULL DEFAULT 1,

    CONSTRAINT UK_Назначения UNIQUE (ДисциплинаID, ГруппаID, Семестр, УчебныйГод),

    CONSTRAINT FK_Назначения_Дисциплины
        FOREIGN KEY (ДисциплинаID) REFERENCES dbo.Дисциплины(ДисциплинаID),
    CONSTRAINT FK_Назначения_Группы
        FOREIGN KEY (ГруппаID) REFERENCES dbo.Группы(ГруппаID),
    CONSTRAINT FK_Назначения_Преподаватели
        FOREIGN KEY (ПреподавательID) REFERENCES dbo.Преподаватели(ПреподавательID)
);
GO

-- ============================================================
-- 8. ОЦЕНКИ
-- ============================================================
CREATE TABLE dbo.Оценки
(
    ОценкаID        INT           IDENTITY(1,1) PRIMARY KEY,
    СтудентID       INT           NOT NULL,
    ДисциплинаID    INT           NOT NULL,
    ПреподавательID INT           NOT NULL,
    ТипРаботы       NVARCHAR(50)  NOT NULL
        CHECK (ТипРаботы IN (
            'Контрольная работа', 'Лабораторная работа',
            'Практическая работа', 'Зачёт', 'Экзамен', 'Реферат', 'Курсовая работа'
        )),
    Оценка          TINYINT       NOT NULL CHECK (Оценка BETWEEN 2 AND 5),
    Дата            DATE          NOT NULL DEFAULT CAST(GETDATE() AS DATE),
    Семестр         TINYINT       NOT NULL DEFAULT 1 CHECK (Семестр BETWEEN 1 AND 2),
    УчебныйГод      NVARCHAR(9)   NOT NULL DEFAULT '2025/2026',
    Комментарий     NVARCHAR(500) NULL,
    ДатаСоздания    DATETIME2     NOT NULL DEFAULT GETDATE(),

    CONSTRAINT FK_Оценки_Студенты
        FOREIGN KEY (СтудентID) REFERENCES dbo.Студенты(СтудентID),
    CONSTRAINT FK_Оценки_Дисциплины
        FOREIGN KEY (ДисциплинаID) REFERENCES dbo.Дисциплины(ДисциплинаID),
    CONSTRAINT FK_Оценки_Преподаватели
        FOREIGN KEY (ПреподавательID) REFERENCES dbo.Преподаватели(ПреподавательID)
);
GO

-- ============================================================
-- 9. ПОСЕЩАЕМОСТЬ
-- ============================================================
CREATE TABLE dbo.Посещаемость
(
    ПосещаемостьID  INT         IDENTITY(1,1) PRIMARY KEY,
    СтудентID       INT         NOT NULL,
    ДисциплинаID    INT         NOT NULL,
    ПреподавательID INT         NOT NULL,
    Дата            DATE        NOT NULL,
    Статус          NCHAR(1)    NOT NULL DEFAULT 'П'
        CHECK (Статус IN ('П', 'Н', 'Б', 'У')),
        -- П = Присутствовал, Н = Отсутствовал, Б = Болезнь, У = Уважительная причина
    Примечание      NVARCHAR(200) NULL,
    ДатаСоздания    DATETIME2   NOT NULL DEFAULT GETDATE(),

    CONSTRAINT UK_Посещаемость UNIQUE (СтудентID, ДисциплинаID, Дата),

    CONSTRAINT FK_Посещаемость_Студенты
        FOREIGN KEY (СтудентID) REFERENCES dbo.Студенты(СтудентID),
    CONSTRAINT FK_Посещаемость_Дисциплины
        FOREIGN KEY (ДисциплинаID) REFERENCES dbo.Дисциплины(ДисциплинаID),
    CONSTRAINT FK_Посещаемость_Преподаватели
        FOREIGN KEY (ПреподавательID) REFERENCES dbo.Преподаватели(ПреподавательID)
);
GO

