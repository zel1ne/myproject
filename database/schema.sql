-- Средний балл студента
CREATE OR ALTER VIEW dbo.vw_СреднийБаллСтудента AS
SELECT
    с.СтудентID,
    п.ФИО,
    г.Название  AS Группа,
    sp.Название AS Специальность,
    с.НомерЗачётки,
    COUNT(о.ОценкаID)               AS КоличествоОценок,
    ROUND(AVG(CAST(о.Оценка AS FLOAT)), 2) AS СреднийБалл,
    SUM(CASE WHEN о.Оценка = 5 THEN 1 ELSE 0 END) AS Пятёрок,
    SUM(CASE WHEN о.Оценка = 4 THEN 1 ELSE 0 END) AS Четвёрок,
    SUM(CASE WHEN о.Оценка = 3 THEN 1 ELSE 0 END) AS Троек,
    SUM(CASE WHEN о.Оценка = 2 THEN 1 ELSE 0 END) AS Двоек
FROM dbo.Студенты с
JOIN dbo.Пользователи   п  ON с.ПользовательID = п.ПользовательID
JOIN dbo.Группы          г  ON с.ГруппаID       = г.ГруппаID
JOIN dbo.Специальности   sp ON г.СпециальностьID = sp.СпециальностьID
LEFT JOIN dbo.Оценки     о  ON с.СтудентID       = о.СтудентID
GROUP BY с.СтудентID, п.ФИО, г.Название, sp.Название, с.НомерЗачётки;
GO

-- Посещаемость студента (%)
CREATE OR ALTER VIEW dbo.vw_ПосещаемостьСтудента AS
SELECT
    по.СтудентID,
    п.ФИО,
    г.Название AS Группа,
    COUNT(*)                                                      AS ВсегоЗанятий,
    SUM(CASE WHEN по.Статус IN ('П', 'У') THEN 1 ELSE 0 END)    AS Присутствовал,
    SUM(CASE WHEN по.Статус = 'Н' THEN 1 ELSE 0 END)            AS Отсутствовал,
    SUM(CASE WHEN по.Статус = 'Б' THEN 1 ELSE 0 END)            AS Болел,
    ROUND(
        SUM(CASE WHEN по.Статус IN ('П','У') THEN 1.0 ELSE 0 END)
        / COUNT(*) * 100, 1
    ) AS ПроцентПосещаемости
FROM dbo.Посещаемость по
JOIN dbo.Студенты     с ON по.СтудентID = с.СтудентID
JOIN dbo.Пользователи п ON с.ПользовательID = п.ПользовательID
JOIN dbo.Группы       г ON с.ГруппаID       = г.ГруппаID
GROUP BY по.СтудентID, п.ФИО, г.Название;
GO

-- Средний балл группы по дисциплинам
CREATE OR ALTER VIEW dbo.vw_УспеваемостьГруппы AS
SELECT
    г.Название  AS Группа,
    д.Название  AS Дисциплина,
    о.УчебныйГод,
    о.Семестр,
    COUNT(о.ОценкаID)                          AS КоличествоОценок,
    ROUND(AVG(CAST(о.Оценка AS FLOAT)), 2)    AS СреднийБалл,
    ROUND(
        SUM(CASE WHEN о.Оценка >= 4 THEN 1.0 ELSE 0 END)
        / COUNT(*) * 100, 1
    )                                          AS КачествоЗнаний
FROM dbo.Оценки           о
JOIN dbo.Студенты         с  ON о.СтудентID    = с.СтудентID
JOIN dbo.Группы           г  ON с.ГруппаID     = г.ГруппаID
JOIN dbo.Дисциплины       д  ON о.ДисциплинаID = д.ДисциплинаID
GROUP BY г.Название, д.Название, о.УчебныйГод, о.Семестр;
GO

